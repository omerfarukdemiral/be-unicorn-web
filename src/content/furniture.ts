//   desk 8 · common 9 · room 7 (size 2) · special 6
// Geometry hints are in cell units: origin = anchor cell center on the floor, y up, the item faces −z (toward
// the wall) at rotation 0. Size-2 items span the anchor cell and the next cell on +x (x ∈ [−0.5, 1.5]).
// Prices scale with the unlock stage (~×3 per stage). moraleAura stays in +3..+8 (PLAN §3.4).
import type { FurnitureItem, PrimitiveHint } from './types'

type V3 = [number, number, number]
const box = (size: V3, pos: V3, color: PrimitiveHint['color'], rot?: V3): PrimitiveHint =>
  rot ? { kind: 'box', size, pos, color, rot } : { kind: 'box', size, pos, color }
const cyl = (r: number, h: number, pos: V3, color: PrimitiveHint['color']): PrimitiveHint => ({
  kind: 'cylinder',
  size: [r, h, r],
  pos,
  color,
})
const sphere = (r: number, pos: V3, color: PrimitiveHint['color']): PrimitiveHint => ({
  kind: 'sphere',
  size: [r, r, r],
  pos,
  color,
})
const cone = (r: number, h: number, pos: V3, color: PrimitiveHint['color']): PrimitiveHint => ({
  kind: 'cone',
  size: [r, h, r],
  pos,
  color,
})

/** Desk body: top, 4 legs, chair. `monitors` 1 or 2; `wide` for bigger tops. */
function deskParts(monitors: 1 | 2, opts: { wide?: boolean; standing?: boolean } = {}): PrimitiveHint[] {
  const w = opts.wide ? 0.9 : 0.8
  const topY = opts.standing ? 0.55 : 0.42
  const legH = topY - 0.025
  const parts: PrimitiveHint[] = [
    box([w, 0.05, 0.5], [0, topY, -0.05], 'primary'),
    box([0.05, legH, 0.05], [-w / 2 + 0.05, legH / 2, -0.25], 'secondary'),
    box([0.05, legH, 0.05], [w / 2 - 0.05, legH / 2, -0.25], 'secondary'),
    box([0.05, legH, 0.05], [-w / 2 + 0.05, legH / 2, 0.15], 'secondary'),
    box([0.05, legH, 0.05], [w / 2 - 0.05, legH / 2, 0.15], 'secondary'),
    // chair
    box([0.34, 0.05, 0.34], [0, 0.26, 0.38], 'accent'),
    box([0.34, 0.3, 0.05], [0, 0.43, 0.55], 'accent'),
    cyl(0.03, 0.24, [0, 0.12, 0.38], '#4A4A4A'),
  ]
  const screenY = topY + 0.17
  if (monitors === 1) {
    parts.push(box([0.34, 0.22, 0.03], [0, screenY, -0.22], '#2B2D42'), box([0.04, 0.1, 0.04], [0, topY + 0.07, -0.22], '#8D99AE'))
  } else {
    parts.push(
      box([0.3, 0.2, 0.03], [-0.17, screenY, -0.2], '#2B2D42', [0, 0.25, 0]),
      box([0.3, 0.2, 0.03], [0.17, screenY, -0.2], '#2B2D42', [0, -0.25, 0]),
      box([0.04, 0.1, 0.04], [0, topY + 0.07, -0.22], '#8D99AE'),
    )
  }
  return parts
}

